import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const root = fileURLToPath(new URL('../', import.meta.url));
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const feed = read('src/pages/studio/FeedYoutube.tsx');
assert.match(feed, /useRecentVideos\('all'\)/);
assert.match(feed, /onClick=\{\(\) => \{ void updateAllChannels\(\); \}\}/);
assert.doesNotMatch(feed, /useQueries|fetchChannelFeed|loadFeedSnapshots|saveFeedSnapshot/);
assert.match(feed, /getFeedChannels\(channels, includeOwnChannels, format\)/);
assert.match(feed, /https:\/\/www.youtube.com\/watch\?v=/);
const recent = read('src/hooks/use-recent-videos.tsx');
assert.match(recent, /scope === 'all' \|\|/);
assert.match(recent, /await fetchChannelFeed\(channelId, since.toISOString\(\)\)/);
assert.match(recent, /await saveChannelVideos\(channelId, cachedVideos/);
assert.match(recent, /if \(!result\?\.success\) throw new Error/);
// Capturas só nas ações de atualização; nenhum efeito inicia atualização do YouTube.
const effects = [...recent.matchAll(/useEffect\(\(\) => \{([\s\S]*?)\n  \},/g)];
assert.ok(effects.length >= 3);
effects.forEach(([, effect]) => assert.doesNotMatch(effect, /updateChannelVideos|updateAllChannels|fetchChannelFeed|getLatestChannelVideos/));
const storage = read('src/hooks/use-video-storage.tsx');
assert.doesNotMatch(storage, /slice\(0, 7\)|youtube\//);
assert.match(storage, /fetchJsonWithDeadline<CacheMap>\('\/api\/videos'\)/);
assert.match(storage, /if \(!response.ok\) throw new Error/);
assert.ok(storage.indexOf('if (!response.ok)') < storage.indexOf('cacheRef.current = { ...cacheRef.current'));
assert.match(storage, /window.addEventListener\(CACHE_CHANGED, reload\)/);
const core = read('api/_core.mjs');
const saveRoute = core.slice(core.indexOf('if (path === "/videos" && method === "POST")'), core.indexOf('if (path.startsWith("/videos/")'));
assert.doesNotMatch(saveRoute, /slice\(0, 7\)/);
assert.match(saveRoute, /videos,\s+channel_deleted/);
// Segurança dos testes: interrompe qualquer tentativa de rede real.
globalThis.fetch = () => { throw new Error('Network forbidden in offline verification'); };
// Exercita a gravação real do hook com React e HTTP simulados, sem montar a aplicação.
const require = createRequire(path.join(root, 'package.json'));
const ts = require('typescript');
let hookSource = storage.replace(/import[^;]+;/g, '');
hookSource = `const useState = value => [value, () => {}];
const useEffect = () => {};
const useCallback = fn => fn;
const useRef = value => ({current: value});
` + hookSource;
const js = ts.transpileModule(hookSource, {compilerOptions: {target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext}}).outputText;
const {useVideoStorage} = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
globalThis.window = {dispatchEvent: () => {}};
let posted;
globalThis.fetch = async (url, options) => {
  assert.equal(url, '/api/videos');
  assert.equal(options.method, 'POST');
  posted = JSON.parse(options.body);
  return new Response('{}');
};
const hook = useVideoStorage();
const many = Array.from({length: 120}, (_, i) => ({videoId: `id-${i}`, publishedAt: '2026-09-30T12:00:00Z', viewCount: i}));
await hook.saveChannelVideos('test-channel', many);
assert.equal(posted.videos.length, 120);
assert.equal(hook.getChannelVideos('test-channel').videos.length, 120);
globalThis.fetch = async () => new Response('{}', {status: 503});
await assert.rejects(hook.saveChannelVideos('test-channel', []), /salvar/);
assert.equal(hook.getChannelVideos('test-channel').videos.length, 120);
await import(pathToFileURL(path.join(root, 'scripts/verify-youtube-feed.mjs')));
console.log('PASS: shared database, complete persistence, manual refresh only, all-channel refresh, preserved failed updates; offline mocked pagination tests.');
